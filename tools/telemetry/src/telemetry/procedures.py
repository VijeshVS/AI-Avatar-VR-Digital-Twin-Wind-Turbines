"""Authored maintenance procedures.

These are data, not prose generated by a model. The copilot may choose which
steps apply and explain them, but it cannot add a step, a tool or a number. That
is the whole point: a language model is good at phrasing and bad at remembering
whether isolation comes before or after opening a nacelle.

The procedures are deliberately schematic — generic tools, no torque values, no
part numbers — because this is a demonstrator. The disclaimer says so and travels
with every response.
"""

from __future__ import annotations

from dataclasses import dataclass

DISCLAIMER = (
    "Demonstrator procedure written for this pilot. It is not a certified "
    "maintenance instruction; follow the OEM manual and the site lock-out/"
    "tag-out procedure."
)


@dataclass(frozen=True)
class Step:
    id: str
    action: str
    detail: str
    tool: str | None = None
    safety: bool = False


@dataclass(frozen=True)
class Procedure:
    component_id: str
    title: str
    tools: tuple[str, ...]
    safety: tuple[str, ...]
    steps: tuple[Step, ...]

    def step_ids(self) -> tuple[str, ...]:
        return tuple(step.id for step in self.steps)

    def safety_ids(self) -> tuple[str, ...]:
        return tuple(step.id for step in self.steps if step.safety)


